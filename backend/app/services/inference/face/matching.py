"""Consent-gated, backend-only face embedding comparison.

This module accepts embeddings generated by an approved detector/recognizer;
it never receives names from pixels and never returns an identity assertion.
Callers must keep the reference vectors in private backend storage.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import sqrt
from typing import Iterable, Mapping, Sequence


@dataclass(frozen=True)
class FaceMatchResult:
    status: str
    profile_id: str | None
    similarity: float
    message: str

    def as_dict(self) -> dict[str, object]:
        return {
            "status": self.status,
            "profileId": self.profile_id,
            "similarity": round(self.similarity, 4),
            "message": self.message,
        }


def cosine_similarity(first: Sequence[float], second: Sequence[float]) -> float:
    if not first or len(first) != len(second):
        raise ValueError("embeddings must be non-empty and have equal dimensions")
    dot = sum(float(a) * float(b) for a, b in zip(first, second))
    first_norm = sqrt(sum(float(value) ** 2 for value in first))
    second_norm = sqrt(sum(float(value) ** 2 for value in second))
    if first_norm == 0 or second_norm == 0:
        raise ValueError("embeddings must have non-zero magnitude")
    return dot / (first_norm * second_norm)


class ConsentGatedFaceMatcher:
    def __init__(self, *, threshold: float = 0.72, enabled: bool = False) -> None:
        self.threshold = max(0.0, min(float(threshold), 1.0))
        self.enabled = enabled

    def compare(
        self,
        probe: Sequence[float],
        references: Iterable[Mapping[str, object]],
    ) -> FaceMatchResult:
        if not self.enabled:
            return FaceMatchResult("disabled", None, 0.0, "Consent-based face matching is disabled.")
        best_id: str | None = None
        best_score = -1.0
        for reference in references:
            profile_id = str(reference.get("profileId") or "").strip()
            vector = reference.get("embedding")
            if not profile_id or not isinstance(vector, (list, tuple)):
                continue
            score = cosine_similarity(probe, vector)
            if score > best_score:
                best_id, best_score = profile_id, score
        if best_id is None or best_score < self.threshold:
            return FaceMatchResult("unknown", None, max(0.0, best_score), "Unknown face — human verification required.")
        return FaceMatchResult(
            "potential_match",
            best_id,
            best_score,
            "Potential face match — human verification required.",
        )
